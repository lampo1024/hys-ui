      点击另一行或列可扩选。点击左上角或按 Ctrl / ⌘ + A 全选。Shift + Space
      选择当前行，Ctrl + Space 选择当前列。也可拖动或按 Shift +
      方向键选择矩形区域。按住 Ctrl / ⌘ 单击单元格可添加离散选区。按住 Ctrl / ⌘ 点击已选中的行号或列标，可从选区中移除该行或列。
