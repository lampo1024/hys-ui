async page => {
  const checks=[],errors=[]
  const check=(name,passed)=>{checks.push({name,pass:!!passed});if(!passed)throw Error(name)}
  page.on('pageerror',error=>errors.push(error.message))
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('http://127.0.0.1:5174/components/hys-tabs')
  await page.locator('#scene-configure [role="tablist"]').waitFor()

  const configure=page.locator('#scene-configure')
  for(const position of ['left','right','bottom','top']){
    await configure.getByRole('combobox',{name:'导航位置 placement'}).click()
    await page.getByRole('option',{name:position,exact:true}).click()
    const geometry=await configure.locator('.hys-ui-tabs-root').evaluate(root=>{
      const nav=root.querySelector('[role="tablist"]').getBoundingClientRect(),content=root.querySelector('.hys-ui-tabs-content').getBoundingClientRect()
      return {nav:{left:nav.left,right:nav.right,top:nav.top,bottom:nav.bottom},content:{left:content.left,right:content.right,top:content.top,bottom:content.bottom}}
    })
    check('Tabs placement '+position,position==='left'?geometry.nav.right<=geometry.content.left+1:position==='right'?geometry.content.right<=geometry.nav.left+1:position==='bottom'?geometry.content.bottom<=geometry.nav.top+1:geometry.nav.bottom<=geometry.content.top+1)
  }
  const keyboard=page.locator('#scene-keyboard')
  await keyboard.getByRole('tab',{name:'总览',exact:true}).focus()
  await page.keyboard.press('ArrowRight')
  check('Manual tab navigation skips disabled and waits for confirmation',await keyboard.getByRole('tab',{name:'活动记录'}).evaluate(button=>button===document.activeElement&&button.getAttribute('aria-selected')==='false'))
  await page.keyboard.press('Enter')
  check('Manual tab confirmation activates numeric value',await keyboard.getByRole('tab',{name:'活动记录'}).getAttribute('aria-selected')==='true')

  const lifecycle=page.locator('#scene-lifecycle')
  await lifecycle.getByRole('textbox',{name:'草稿一草稿'}).fill('保留的独立草稿')
  await lifecycle.getByRole('tab',{name:'草稿二',exact:true}).click()
  await lifecycle.getByRole('textbox',{name:'草稿二草稿'}).fill('第二份草稿')
  await lifecycle.getByRole('tab',{name:'草稿一',exact:true}).click()
  check('Tab panels retain independent drafts',await lifecycle.getByRole('textbox',{name:'草稿一草稿'}).inputValue()==='保留的独立草稿')
  await lifecycle.getByRole('checkbox',{name:'离开时销毁内容',exact:true}).check()
  await lifecycle.getByRole('tab',{name:'草稿二',exact:true}).click()
  await lifecycle.getByRole('tab',{name:'草稿一',exact:true}).click()
  check('Destroy-on-hide resets only recreated tab panels',await lifecycle.getByRole('textbox',{name:'草稿一草稿'}).inputValue()==='')

  const dynamic=page.locator('#scene-dynamic')
  const initial=await dynamic.getByRole('tab').count()
  await dynamic.getByRole('button',{name:'添加页签',exact:true}).click()
  check('Editable tabs add an active item',await dynamic.getByRole('tab').count()===initial+1&&await dynamic.getByRole('tab',{name:'文档 3',exact:true}).getAttribute('aria-selected')==='true')
  await dynamic.getByRole('checkbox',{name:'阻止关闭（模拟未保存内容）',exact:true}).check()
  await dynamic.getByRole('button',{name:'关闭文档 3',exact:true}).click()
  await page.waitForTimeout(350)
  check('Close guard keeps unsaved tab',await dynamic.getByRole('tab',{name:'文档 3',exact:true}).count()===1)
  await dynamic.getByRole('checkbox',{name:'阻止关闭（模拟未保存内容）',exact:true}).uncheck()
  await dynamic.getByRole('button',{name:'关闭文档 3',exact:true}).click()
  await page.waitForTimeout(350)
  check('Guarded close updates host-owned list',await dynamic.getByRole('tab').count()===initial&&await dynamic.getByRole('button',{name:'关闭固定页签',exact:true}).count()===0)

  const guard=page.locator('#scene-guard')
  await guard.getByRole('tab',{name:'预览',exact:true}).click()
  await page.waitForTimeout(500)
  check('Tab switch guard rejects unsaved changes',await guard.getByRole('tab',{name:'编辑内容',exact:true}).getAttribute('aria-selected')==='true')
  await guard.getByRole('checkbox',{name:'存在未保存修改',exact:true}).uncheck()
  await guard.getByRole('tab',{name:'预览',exact:true}).click()
  await guard.getByRole('tab',{name:'发布设置',exact:true}).click()
  await page.waitForTimeout(500)
  check('Latest asynchronous tab request wins',await guard.getByRole('tab',{name:'发布设置',exact:true}).getAttribute('aria-selected')==='true')

  const overflow=page.locator('#scene-overflow')
  await overflow.getByRole('button',{name:'切换到最后一项',exact:true}).click()
  await page.waitForTimeout(50)
  check('Programmatic selection reveals the last tab',await overflow.locator('[role="tablist"]').evaluate(nav=>{const tab=nav.querySelector('[aria-selected="true"]'),n=nav.getBoundingClientRect(),t=tab.getBoundingClientRect();return nav.scrollLeft>0&&t.left>=n.left-1&&t.right<=n.right+1}))
  await overflow.getByRole('checkbox',{name:'使用简短标签',exact:true}).check()
  await page.waitForTimeout(50)
  check('Changing label widths recalculates overflow controls',await overflow.locator('.hys-ui-tab-scroll').count()===0)
  await lifecycle.locator('summary').click()
  await lifecycle.locator('.source-code code').waitFor()
  check('New source example is formatted and loadable',(await lifecycle.locator('.source-code code').textContent()).includes('DraftEditor'))
  await page.locator('.docs-sidebar a[href="/components/hys-accordion"]').click()
  await page.locator('#scene-selection .hys-ui-ex-accordion').waitFor()

  const selection=page.locator('#scene-selection')
  await selection.getByRole('button',{name:'反转显示顺序',exact:true}).click()
  check('Accordion selection follows stable keys after reorder',await selection.getByRole('button',{name:'安全设置',exact:true}).getAttribute('aria-expanded')==='true')
  await selection.getByRole('button',{name:'全部展开',exact:true}).click()
  check('Accordion supports multiple controlled panels',await selection.locator('.hys-ui-accordion-trigger[aria-expanded="true"]').count()===3)
  const accordionLifecycle=page.locator('#scene-lifecycle')
  await accordionLifecycle.getByRole('textbox',{name:'面板内草稿'}).fill('折叠草稿')
  await accordionLifecycle.getByRole('button',{name:'编辑草稿',exact:true}).click()
  await page.waitForTimeout(250)
  await accordionLifecycle.getByRole('button',{name:'编辑草稿',exact:true}).click()
  check('Accordion preserves local draft when requested',await accordionLifecycle.getByRole('textbox',{name:'面板内草稿'}).inputValue()==='折叠草稿')
  await accordionLifecycle.getByRole('checkbox',{name:'收起时销毁内容'}).check()
  await accordionLifecycle.getByRole('button',{name:'编辑草稿',exact:true}).click()
  await page.waitForTimeout(250)
  await accordionLifecycle.getByRole('button',{name:'编辑草稿',exact:true}).click()
  check('Accordion destruction creates a fresh editor',await accordionLifecycle.getByRole('textbox',{name:'面板内草稿'}).inputValue()==='')
  const custom=page.locator('#scene-custom')
  const before=await custom.locator('.hys-ui-accordion-trigger[aria-expanded="true"]').count()
  await custom.getByRole('button',{name:'保存偏好',exact:true}).first().click()
  check('Accordion extra actions do not toggle content',await custom.locator('.hys-ui-accordion-trigger[aria-expanded="true"]').count()===before)
  const accordionKeyboard=page.locator('#scene-keyboard')
  await accordionKeyboard.getByRole('button',{name:'第一项',exact:true}).focus()
  await page.keyboard.press('ArrowDown')
  check('Accordion keyboard navigation skips disabled headers',await accordionKeyboard.getByRole('button',{name:'第三项',exact:true}).evaluate(button=>button===document.activeElement))
  await page.keyboard.press('Space')
  check('Accordion native Space activation expands content',await accordionKeyboard.getByRole('button',{name:'第三项',exact:true}).getAttribute('aria-expanded')==='true')
  const asyncPanel=page.locator('#scene-async')
  await asyncPanel.getByRole('button',{name:'受保护内容',exact:true}).click()
  await page.waitForTimeout(450)
  check('Accordion expansion guard can refuse',await asyncPanel.getByRole('button',{name:'受保护内容',exact:true}).getAttribute('aria-expanded')==='false')
  await asyncPanel.getByRole('checkbox',{name:'条件未满足，阻止展开'}).uncheck()
  await asyncPanel.getByRole('button',{name:'受保护内容',exact:true}).click()
  await page.waitForTimeout(450)
  check('Accordion expansion guard can resolve',await asyncPanel.getByRole('button',{name:'受保护内容',exact:true}).getAttribute('aria-expanded')==='true')

  await page.goto('http://127.0.0.1:5174/components/hys-steps')
  await page.locator('#scene-configure .hys-ui-ex-steps').waitFor()
  await page.locator('#scene-configure').getByRole('button',{name:'下一步',exact:true}).click()
  await page.locator('#scene-configure .demo-row').getByRole('button',{name:'完成',exact:true}).click()
  check('Step examples can reach all-complete boundary',await page.locator('#scene-configure [aria-current="step"]').count()===0&&await page.locator('#scene-configure .hys-ui-done').count()===3)
  check('Individual step status takes precedence',await page.locator('#scene-states .hys-ui-step-error').count()===1)
  await page.goto('http://127.0.0.1:5174/components/hys-breadcrumb')
  await page.locator('#scene-custom .hys-ui-ex-breadcrumb').waitFor()
  await page.locator('#scene-custom').getByRole('button',{name:'首页',exact:true}).click()
  check('Breadcrumb host navigation slot works',(await page.locator('#scene-custom output').textContent()).includes('首页'))
  check('Breadcrumb disabled and external states render correctly',await page.locator('#scene-states .hys-ui-ex-breadcrumb [aria-disabled="true"]').count()===1&&(await page.locator('#scene-states a[target="_blank"]').getAttribute('rel')).includes('noopener'))

  for(const name of ['hys-tabs','hys-accordion','hys-steps','hys-breadcrumb']){
    await page.setViewportSize({width:390,height:844})
    await page.goto('http://127.0.0.1:5174/components/'+name)
    await page.locator('#scene-configure [data-hys-ui]').first().waitFor()
    check(name+' narrow page does not overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  }
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('http://127.0.0.1:5174/components/hys-tabs')
  await page.locator('#scene-configure').scrollIntoViewIfNeeded()
  await page.screenshot({path:'output/playwright/navigation-tabs.png'})
  check('No browser runtime errors',errors.length===0)
  return {checks,errors}
}
