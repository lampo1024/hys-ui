async page => {
  const base=page.url().includes('github.io')?new URL(page.url()).origin+'/hys-ui':'http://127.0.0.1:5174'
  const checks=[],errors=[],warnings=[]
  const check=(name,pass)=>{checks.push({name,pass:!!pass});if(!pass)throw Error(name)}
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',e=>{if(e.type()==='warning'&&e.text().includes('[Vue warn]'))warnings.push(e.text())})
  page.setDefaultTimeout(12000)
  const scene=name=>page.locator('#scene-'+name)
  const table=s=>s.locator('.hys-ui-virtual-table')
  const port=s=>s.locator('.hys-ui-v4-table-viewport')
  const body=s=>s.locator('.hys-ui-virtual-space [role=row]')
  const row=(s,id)=>body(s).and(s.locator('[data-row-key="number:'+id+'"]'))
  const footer=s=>s.locator('.hys-ui-virtual-footer')
  const button=(s,name)=>s.getByRole('button',{name,exact:true})
  const cell=(scope,key)=>scope.locator('[data-column-key="'+key+'"]')
  const sorted=(s,key)=>s.locator('[role=columnheader][data-column-key="'+key+'"]')
  const choose=async(s,label,value)=>{
    await s.getByRole('combobox',{name:label,exact:true}).click()
    await page.getByRole('option',{name:value,exact:true}).click()
  }
  const position=s=>port(s).evaluate(p=>({top:p.scrollTop,left:p.scrollLeft,width:p.clientWidth}))
  const getGeometry=s=>table(s).evaluate(t=>{
    const p=t.querySelector('.hys-ui-v4-table-viewport'),pr=p.getBoundingClientRect()
    const header=t.querySelector('.hys-ui-v4-table-head'),hr=header.getBoundingClientRect()
    const fixed=t.querySelector('.hys-ui-virtual-fixed-row'),fr=fixed?.getBoundingClientRect()
    const row=[...t.querySelectorAll('.hys-ui-virtual-space [role=row]')].find(e=>e.getBoundingClientRect().top >= (fr??hr).bottom-1)
    const box=(container,key)=>{const r=container?.querySelector('[data-column-key="'+key+'"]')?.getBoundingClientRect();return r?{left:r.left,right:r.right,top:r.top,width:r.width}:null}
    return {left:pr.left,right:pr.left+p.clientWidth,top:pr.top,headTop:hr.top,fixedTop:fr?.top,fixedBottom:fr?.bottom,headBottom:hr.bottom,rowTop:row?.getBoundingClientRect().top,
      header:['id','status','remarks'].map(k=>box(header,k)),cells:['id','status','remarks'].map(k=>box(row,k)),
      headerBg:getComputedStyle(header.querySelector('[data-column-key=id]')).backgroundColor,
      centerBg:getComputedStyle(header.querySelector('[data-column-key=remarks]')).backgroundColor}
  })
  const near=(a,b)=>Number.isFinite(a)&&Number.isFinite(b)&&Math.abs(a-b)<=1.5
  const active=grid=>grid.evaluate(el=>{
    const target=document.getElementById(el.getAttribute('aria-activedescendant'))
    return target?{key:target.dataset.columnKey,row:target.closest('[data-row-key]')?.dataset.rowKey,focused:document.activeElement===el}:null
  })
  try {
    await page.setViewportSize({width:1440,height:1050})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.goto(base+'/components/hys-virtual-table/')
    const basic=scene('basic')
    await basic.waitFor()
    check('Legacy table renders a bounded row window',await body(basic).count()<24)
    await button(basic,'定位任务 #5000').click()
    await row(basic,5000).waitFor()
    check('A row key locates a distant record', (await position(basic)).top>190000)
    await button(basic,'跳到末行').click()
    await row(basic,10000).waitFor()
    check('The last record is rendered at the bottom',await body(basic).last().getAttribute('data-row-key')==='number:10000')
    await button(basic,'回到首行').click()
    check('Top position restores the first row',(await position(basic)).top===0&&await body(basic).first().getAttribute('data-row-key')==='number:1')

    const fixed=scene('fixed')
    await fixed.scrollIntoViewIfNeeded()
    await button(fixed,'查看发货备注').click()
    await port(fixed).evaluate(p=>{p.scrollTop=1250})
    await page.waitForFunction(()=>{const row=document.querySelector('#scene-fixed .hys-ui-virtual-space [role=row]');return Number(row?.dataset.rowKey?.split(':')[1])>20})
    const g=await getGeometry(fixed)
    check('Vertical scrolling keeps header and fixed summary at top',near(g.top,g.headTop)&&near(g.headBottom,g.fixedTop))
    check('Left pinned header and body share viewport edge',near(g.header[0]?.left,g.left)&&near(g.cells[0]?.left,g.left))
    check('Right pinned header and body share viewport edge',near(g.header[1]?.right,g.right)&&near(g.cells[1]?.right,g.right))
    check('Middle column header and body stay aligned',near(g.header[2]?.left,g.cells[2]?.left)&&near(g.header[2]?.right,g.cells[2]?.right))
    check('Fixed headers use the same opaque fill as regular headers',g.headerBg===g.centerBg&&g.headerBg!=='rgba(0, 0, 0, 0)')
    check('Data starts below the fixed area',g.rowTop>=g.fixedBottom-1)
    await fixed.screenshot({path:'output/playwright/virtual-table-fixed-'+page.context().browser()?.browserType().name()+'.png'})

    const wide=scene('wide')
    await button(wide,'定位第 3200 行 / 指标 300').click()
    await cell(row(wide,3200),'m300').waitFor()
    check('Large dataset jumps across both axes', (await position(wide)).top>130000&&(await position(wide)).left>30000)
    check('Column and row window bound rendered DOM',await table(wide).locator('[role=columnheader]').count()<17&&await body(wide).count()<24&&await table(wide).locator('[role=cell]').count()<350)
    check('Fixed sides stay rendered across distant windows',await cell(row(wide,3200),'id').count()===1&&await cell(row(wide,3200),'series').count()===1)
    await button(wide,'查看最后一个指标').click()
    await sorted(wide,'m400').waitFor()
    check('Far right column remains accessible',(await cell(row(wide,3200),'m400').innerText()).trim()===String((3200*17+399*3)%1000))
    await button(wide,'回到起点').click()
    check('Returning to origin shows the original window',await sorted(wide,'m1').count()===1&&await sorted(wide,'m400').count()===0)

    const selection=scene('selection')
    await selection.scrollIntoViewIfNeeded()
    const one=selection.locator('[data-row-key="number:1"]')
    check('Disabled row cannot be checked',await selection.getByRole('checkbox',{name:'选择第 1 行',exact:true}).isDisabled())
    await selection.getByRole('checkbox',{name:'选择全部行',exact:true}).check()
    check('Select all includes eligible offscreen rows',(await footer(selection).innerText()).includes('已选 71 项'))
    await button(selection,'清空选择').click()
    await cell(one,'name').click()
    await cell(selection.locator('[data-row-key="number:4"]'),'name').click({modifiers:['Shift']})
    check('Shift click selects the inclusive range',(await footer(selection).innerText()).includes('已选 4 项'))
    await selection.getByRole('checkbox',{name:'接受受控更新',exact:true}).uncheck()
    await button(selection,'额度降序').click()
    await button(selection,'清空选择').click()
    check('Rejected updates preserve sort and checks',await sorted(selection,'quota').getAttribute('aria-sort')==='none'&&(await footer(selection).innerText()).includes('已选 4 项'))
    await selection.getByRole('checkbox',{name:'接受受控更新',exact:true}).check()
    await button(selection,'额度降序').click()
    check('Direct sort controls update order and aria state',await sorted(selection,'quota').getAttribute('aria-sort')==='descending'&&(await cell(body(selection).first(),'quota').innerText())==='99')
    await choose(selection,'选择模式','单选')
    const radios=selection.locator('input[type=radio]:enabled')
    await radios.nth(0).check()
    await radios.nth(1).check()
    check('Radio selection stays single',await radios.nth(1).isChecked()&&!await radios.nth(0).isChecked()&&(await footer(selection).innerText()).includes('已选 1 项'))

    const remote=scene('remote')
    await button(remote,'销量降序').click()
    await remote.getByText('正在读取排序结果…',{exact:true}).waitFor()
    check('Remote sorting preserves old rows under an overlay',await body(remote).count()>0)
    await remote.getByText('正在读取排序结果…',{exact:true}).waitFor({state:'hidden'})
    const sales=await cell(body(remote),'sales').allTextContents()
    check('Host response orders remote data',sales.every((value,i)=>i===0||Number(sales[i-1])>=Number(value)))

    const append=scene('append')
    await append.getByRole('checkbox',{name:'模拟下次加载失败',exact:true}).check()
    await button(append,'定位当前末尾').click()
    const bottom=(await position(append)).top
    await button(append,'重试加载').waitFor()
    check('Failed append preserves existing data',(await footer(append).innerText()).includes('已加载 60 / 240'))
    await button(append,'重试加载').click()
    await append.getByText(/已加载 120 \/ 240/).waitFor()
    check('Successful append retains the original scroll offset',near((await position(append)).top,bottom))

    const keyboard=scene('keyboard'),grid=table(keyboard)
    await button(keyboard,'定位并聚焦').click()
    check('Focus API reaches an offscreen cell',(await active(grid))?.row==='number:1200'&&(await active(grid))?.key==='location'&&(await active(grid))?.focused)
    await grid.press('ArrowDown')
    check('Keyboard movement tracks logical row',(await active(grid))?.row==='number:1201')
    await grid.press('Space')
    await grid.press('ArrowDown')
    await grid.press('Shift+Space')
    check('Keyboard selection extends across rows',(await footer(keyboard).innerText()).includes('已选 2 项'))
    await grid.press('Control+End')
    check('Control End locates the last cell',(await active(grid))?.row==='number:1500'&&(await active(grid))?.key==='stage')

    const templates=scene('templates')
    check('Nested field and formatter produce expected content',(await cell(body(templates).first(),'supplier').innerText())==='明远'&&(await cell(body(templates).first(),'amount').innerText()).includes('450.00'))
    check('Custom cell can override the default title',await cell(body(templates).first(),'amount').getAttribute('title')==='订单 PO-001 应付金额')
    await cell(body(templates).first(),'number').click()
    check('Row click returns the original record',(await templates.locator('output').innerText())==='当前订单 PO-001')

    const lifecycle=scene('lifecycle')
    await button(lifecycle,'缩小容器').click()
    await page.waitForFunction(()=>document.querySelector('#scene-lifecycle .hys-ui-v4-table-viewport').clientWidth<=420)
    await button(lifecycle,'定位资产 500').click()
    const cached=await position(lifecycle)
    check('Container resize exposes a real horizontal scroll window',cached.width<=420&&cached.left>0&&cached.top>0)
    await button(lifecycle,'离开表格').click()
    await table(lifecycle).waitFor({state:'detached'})
    await button(lifecycle,'返回表格').click()
    await page.waitForFunction(({top,left})=>{const p=document.querySelector('#scene-lifecycle .hys-ui-v4-table-viewport');return p&&Math.abs(p.scrollTop-top)<=1&&Math.abs(p.scrollLeft-left)<=1},cached)
    check('KeepAlive restores both scroll offsets',near((await position(lifecycle)).top,cached.top)&&near((await position(lifecycle)).left,cached.left))

    const states=scene('states')
    await states.getByText('暂无报表',{exact:true}).waitFor()
    await button(states,'查看报表').click()
    check('Empty slot can provide a working recovery action',await body(states).count()>0)
    await choose(states,'表格状态','替换加载')
    check('Replace loading hides data rows',await body(states).count()===0)
    await choose(states,'表格状态','覆盖加载')
    check('Overlay loading preserves data rows',await body(states).count()>0&&await table(states).getAttribute('aria-busy')==='true')
    await choose(states,'表格状态','禁用')
    check('Disabled table blocks selection',await states.getByRole('checkbox',{name:'选择全部行',exact:true}).isDisabled())

    await page.setViewportSize({width:390,height:850})
    await fixed.scrollIntoViewIfNeeded()
    check('Mobile page keeps horizontal overflow inside the table',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
    const mobile=await getGeometry(fixed)
    check('Mobile keeps both pinned edges aligned',near(mobile.header[0]?.left,mobile.left)&&near(mobile.header[1]?.right,mobile.right))
    await fixed.screenshot({path:'output/playwright/virtual-table-mobile-'+page.context().browser()?.browserType().name()+'.png'})
    await page.setViewportSize({width:1440,height:1050})
    await choose(page,'文档主题','深色')
    check('VirtualTable follows the active theme',await table(fixed).getAttribute('data-hys-theme')==='dark')
    await fixed.screenshot({path:'output/playwright/virtual-table-dark-'+page.context().browser()?.browserType().name()+'.png'})
    await choose(page,'文档主题','科技蓝')
    check('No browser runtime errors',errors.length===0)
    check('No Vue warnings',warnings.length===0)
    return {checks,errors,warnings}
  }catch(error){return {error:String(error),checks,errors,warnings,url:page.url()}}
}
