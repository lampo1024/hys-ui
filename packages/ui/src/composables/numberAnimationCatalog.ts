type Category = (typeof categories)[number];
export type HysNumberAnimationCategory = Category["id"];
export type HysNumberAnimationName = Category["entries"][number][0];

export interface HysNumberAnimationEntry {
  name: HysNumberAnimationName;
  label: string;
  english?: string;
  category: HysNumberAnimationCategory;
  variant: number;
}

export const hysNumberAnimationCategories = categories.map(({ id, label }) => ({
  id,
  label,
}));
export const hysNumberAnimationCatalog: readonly HysNumberAnimationEntry[] =
  categories.flatMap(({ id, entries }) =>
    entries.map(([name, label, english], variant) => ({
      name,
      label,
      english,
      category: id,
      variant,
    })),
  );
